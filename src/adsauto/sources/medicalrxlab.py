"""MedicalRxLab connector.

medicalrxlab.com is a React storefront with a Node API. Its WooCommerce
instance (/commerce/) is a closed backend whose Store API answers 503 by
design, so the WooCommerce connector cannot be used. The public truth is

    GET https://medicalrxlab.com/api/catalog

One JSON document: ``products[]`` with ``variants[]``. Every variant already
carries its D2C SKU (``MRX-<CODE>[-BLEND]-<DOSE>-<1V|BX10>``), generated by
the site's ``shared/sku.mjs``. The SKU is used as ``g:id`` unchanged so this
feed and the site's own ``/feeds/google-merchant.xml`` agree on identifiers.
The connector re-derives the dose and pack tokens from the variant label with
a port of ``sku.mjs`` and refuses a SKU that disagrees with its own label —
it never invents an identifier.

Raw response: the whole payload is kept on the extractor (``raw_response``,
``raw_sha256``, ``fetched_at``) so every feed row can be traced back to the
exact API response it came from. ``save_raw()`` writes it next to the feed.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
from datetime import datetime, timezone
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from typing import Any, Iterable, Iterator

import httpx

from ..feed import policy as feed_policy
from ..models import Product, strip_html

log = logging.getLogger(__name__)

SITE = "https://medicalrxlab.com"
CATALOG_PATH = "/api/catalog"
PRODUCT_PATH = "/products/{handle}"      # verified live: /product/<handle> is 404
BRAND = "MedicalRxLab"
CURRENCY = "USD"
GOOGLE_PRODUCT_CATEGORY = (
    "Business & Industrial > Science & Laboratory > Laboratory Supplies"
)

# --- port of shared/sku.mjs ------------------------------------------------

D2C_PREFIX = "MRX"
D2C_SKU = re.compile(r"^MRX-([A-Z0-9]{2,16})(-BLEND)?-([A-Z0-9]+)-(1V|BX\d+|PK\d+|EA)$")
_UNIT = re.compile(r"(\d[\d,]*(?:\.\d+)?)\s*(mg|mcg|iu|ml|g)\b", re.IGNORECASE)


def dose_token(strength: str) -> str:
    """Port of ``doseToken`` from sku.mjs. Same input, same token.

    "5mg" -> 5MG, "0.1mg" -> 100MCG, "20mg total (10mg + 10mg)" -> 20MG,
    "10mL kit" -> 10MLKIT. Raises when the label carries no amount+unit.
    """
    label = str(strength or "").split("·")[0]
    label = re.sub(r"\s*\(.*\)\s*$", "", label)
    label = re.sub(r"\s*x\s*\d+\s*vials?\b", "", label, flags=re.IGNORECASE)
    label = re.sub(r"\btotal\b", "", label, flags=re.IGNORECASE).strip()
    match = _UNIT.search(label)
    if not match:
        raise ValueError(f'No dose (amount and unit) in strength "{strength}".')
    amount = float(match.group(1).replace(",", ""))
    unit = match.group(2).upper()
    if amount <= 0:
        raise ValueError(f'Invalid dose amount in strength "{strength}".')
    if unit == "MG" and amount < 1:
        amount = round(amount * 1000)
        unit = "MCG"
    number = str(int(amount)) if float(amount).is_integer() else str(amount)
    number = number.replace(".", "P")
    rest = label[: match.start()] + " " + label[match.end():]
    rest = re.sub(r"\bx\b", " ", rest, flags=re.IGNORECASE)
    rest = re.sub(r"[^a-z0-9]+", "", rest, flags=re.IGNORECASE).upper()
    return f"{number}{unit}{rest}"


def pack_token(vials: int | None, pack: str | None) -> str:
    """Pack token: a single vial is 1V, a kit of N vials is BX<N>."""
    if vials == 1 or pack == "single":
        return "1V"
    if vials and vials > 1:
        return f"BX{int(vials)}"
    raise ValueError(f'No SKU pack token for pack "{pack}" / vials {vials!r}.')


def parse_sku(sku: str) -> dict[str, str] | None:
    m = D2C_SKU.match(sku or "")
    if not m:
        return None
    return {
        "code": m.group(1),
        "blend": bool(m.group(2)),
        "dose": m.group(3),
        "pack": m.group(4),
    }


# --- field mapping ----------------------------------------------------------

_MONEY_CENT = Decimal("0.01")


def money(variant: dict[str, Any]) -> Decimal | None:
    """Single-unit price.

    The live payload carries ``amount`` in dollars (20.99). If a ``unitAmount``
    in cents is present it wins, since integers survive JSON better than
    floats. Both are quantized to cents.
    """
    if variant.get("unitAmount") not in (None, ""):
        return (Decimal(str(variant["unitAmount"])) / 100).quantize(
            _MONEY_CENT, rounding=ROUND_HALF_UP
        )
    raw = variant.get("amount")
    if raw in (None, ""):
        return None
    try:
        return Decimal(str(raw)).quantize(_MONEY_CENT, rounding=ROUND_HALF_UP)
    except ArithmeticError:
        log.warning("unparsable amount: %r", raw)
        return None


def availability_of(variant: dict[str, Any]) -> str:
    status = (variant.get("availabilityStatus") or "").lower()
    if status in ("in_stock", "backorder", "preorder"):
        return status
    if status in ("out_of_stock", "unavailable"):
        return "out_of_stock"
    return "in_stock" if variant.get("available") else "out_of_stock"


def dose_label(variant: dict[str, Any]) -> str:
    """"5mg · 1 vial" -> "5mg"; "20mg total (10mg + 10mg) · 10-vial kit" -> "20mg total (10mg + 10mg)"."""
    title = str(variant.get("title") or "")
    return title.split("·")[0].strip()


def pack_label(variant: dict[str, Any]) -> str:
    vials = variant.get("vials")
    if vials == 1 or variant.get("pack") == "single":
        return "Single vial"
    if vials:
        return f"Box of {int(vials)}"
    return "Kit"


_BIOREGULATOR = re.compile(r"\bbioregulat", re.IGNORECASE)
_NOT_PEPTIDE = re.compile(r"\bnot a peptide\b", re.IGNORECASE)


def product_class(product: dict[str, Any]) -> str:
    """product_type from what the catalog itself says.

    "Supplies" is a lab consumable. A description that calls the item a
    bioregulator classes it so; one that says "not a peptide" is a research
    compound. Everything else on this site is a research peptide; blends
    keep a sub-path.
    """
    category = (product.get("category") or "").strip()
    text = " ".join(
        str(product.get(k) or "") for k in ("title", "subtitle", "description")
    )
    if category == "Supplies":
        return "Laboratory supplies"
    if _BIOREGULATOR.search(text):
        return "Bioregulators"
    if _NOT_PEPTIDE.search(text):
        return "Research compounds"
    if category == "Blends":
        return "Research peptides > Blends"
    return "Research peptides"


_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])\s+")
RESEARCH_ONLY = "Supplied for laboratory research use only. Not for human or veterinary use."


def describe(product: dict[str, Any], notes: list[str] | None = None) -> str:
    """Plain-text, research-use-only description.

    Rules, all deterministic:
    1. HTML is stripped.
    2. An import-time placeholder ("listed in our sourcing catalog ...") is
       not a product description. It is replaced by a description built
       only from catalog fields (title, size, category) plus the
       research-use statement. Nothing is invented.
    3. Any sentence carrying a health claim or human-use/dosing wording is
       dropped (same patterns as the P001/P002 policy check), so claim-like
       language in the source never reaches the feed. Drug names (P003)
       are the product's identity and stay.
    """
    pid = str(product.get("id") or "")
    text = strip_html(product.get("description"))
    if feed_policy.PLACEHOLDER_PATTERNS.search(text):
        if notes is not None:
            notes.append(f"{pid}: placeholder description on site, replaced by field-derived text")
        text = ""
    kept: list[str] = []
    for sentence in _SENTENCE_SPLIT.split(text):
        if not sentence.strip():
            continue
        if feed_policy.CLAIM_PATTERNS.search(sentence) or feed_policy.HUMAN_USE_PATTERNS.search(sentence):
            if notes is not None:
                notes.append(f"{pid}: dropped sentence {sentence.strip()!r}")
            continue
        kept.append(sentence.strip())
    if not kept:
        title = str(product.get("title") or "").strip()
        size = str(product.get("size") or "").strip()
        kind = product_class(product).split(" > ")[0].rstrip("s").lower()
        kept = [f"{title}: {kind} for laboratory research, {size}." if size else f"{title}: {kind} for laboratory research."]
    joined = " ".join(kept)
    if "research use only" not in joined.lower():
        joined = f"{joined} {RESEARCH_ONLY}"
    return joined.strip()


def absolute(site: str, url: str | None) -> str:
    if not url:
        return ""
    if url.startswith("http://") or url.startswith("https://"):
        return url
    return f"{site.rstrip('/')}/{url.lstrip('/')}"


def variant_image(site: str, product: dict[str, Any], variant: dict[str, Any]) -> str:
    """Box render for the dose, else the product box, else the vial image."""
    image = product.get("image") or {}
    by_dose = image.get("boxByDose") or {}
    candidates = (
        by_dose.get(str(variant.get("dose") or "")),
        image.get("box"),
        image.get("url"),
    )
    for url in candidates:
        if url:
            return absolute(site, url)
    return ""


def is_public(product: dict[str, Any]) -> bool:
    return not (product.get("draft") or product.get("noindex") or product.get("sample"))


class MedicalRxLabExtractor:
    """Same interface as ``WooExtractor``: ``fetch_catalog()``, ``expand()``, ``run()``."""

    source = "medicalrxlab"

    def __init__(
        self,
        base_url: str = SITE,
        offer_prefix: str = "medicalrxlab",
        timeout: float = 30.0,
        client: httpx.Client | None = None,
    ) -> None:
        self.base = base_url.rstrip("/")
        self.prefix = offer_prefix  # kept for interface parity; g:id is the SKU
        self._client = client or httpx.Client(
            timeout=timeout,
            headers={"User-Agent": "adsauto-feed/0.1"},
            follow_redirects=True,
        )
        self.raw_response: dict[str, Any] | None = None
        self.raw_sha256: str | None = None
        self.fetched_at: str | None = None
        self.skipped: list[dict[str, str]] = []
        self.notes: list[str] = []

    # --- network ---------------------------------------------------------

    @property
    def catalog_url(self) -> str:
        return f"{self.base}{CATALOG_PATH}"

    def fetch_catalog(self) -> dict[str, Any]:
        resp = self._client.get(self.catalog_url)
        resp.raise_for_status()
        self._record(resp.content)
        return self.raw_response  # type: ignore[return-value]

    def _record(self, body: bytes) -> None:
        self.raw_response = json.loads(body)
        self.raw_sha256 = hashlib.sha256(body).hexdigest()
        self.fetched_at = datetime.now(timezone.utc).isoformat()
        log.info(
            "catalog fetched: %d products, sha256 %s",
            len(self.raw_response.get("products") or []),
            self.raw_sha256[:12],
        )

    def load_catalog(self, path: str | Path) -> dict[str, Any]:
        """Offline path: the same payload from disk (fixtures, replays)."""
        self._record(Path(path).read_bytes())
        return self.raw_response  # type: ignore[return-value]

    def save_raw(self, path: str | Path) -> Path:
        """Write the raw response plus provenance next to the feed."""
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            json.dumps(
                {
                    "source": self.source,
                    "endpoint": self.catalog_url,
                    "fetched_at": self.fetched_at,
                    "sha256": self.raw_sha256,
                    "payload": self.raw_response,
                },
                ensure_ascii=False,
                indent=1,
            ),
            encoding="utf-8",
        )
        return out

    def provenance(self) -> dict[str, Any]:
        return {
            "source": self.source,
            "endpoint": self.catalog_url,
            "fetched_at": self.fetched_at,
            "sha256": self.raw_sha256,
        }

    # --- mapping ---------------------------------------------------------

    def _skip(self, product_id: str, variant_id: str | None, reason: str) -> None:
        self.skipped.append(
            {"product": product_id, "variant": variant_id or "", "reason": reason}
        )
        log.warning("skipped %s/%s: %s", product_id, variant_id, reason)

    def variant_to_product(
        self,
        product: dict[str, Any],
        variant: dict[str, Any],
        description: str | None = None,
    ) -> Product | None:
        pid = str(product.get("id") or "")
        vid = str(variant.get("id") or "")
        sku = str(variant.get("sku") or "").strip()
        parsed = parse_sku(sku)
        if not parsed:
            self._skip(pid, vid, f"no D2C SKU on variant (got {sku!r})")
            return None

        # Guard: the SKU must agree with the label it was generated from.
        try:
            expected_dose = dose_token(dose_label(variant))
            expected_pack = pack_token(variant.get("vials"), variant.get("pack"))
        except ValueError as exc:
            self._skip(pid, vid, str(exc))
            return None
        if (parsed["dose"], parsed["pack"]) != (expected_dose, expected_pack):
            self._skip(
                pid, vid,
                f"SKU {sku} disagrees with label {variant.get('title')!r}: "
                f"expected -{expected_dose}-{expected_pack}",
            )
            return None

        name = str(product.get("title") or "").strip()
        dose = dose_label(variant)
        pack = pack_label(variant)
        label = f"{dose} · {pack}"
        handle = str(product.get("handle") or "")

        return Product(
            offer_id=sku,
            item_group_id=parsed["code"],
            source_id=None,
            sku=sku,
            title=f"{name} {dose} – {pack}",
            description=description if description is not None else describe(product, self.notes),
            link=f"{self.base}{PRODUCT_PATH.format(handle=handle)}?variant={vid}",
            image_link=variant_image(self.base, product, variant),
            price=money(variant),
            currency=str(variant.get("currency") or product.get("currency") or CURRENCY),
            availability=availability_of(variant),  # type: ignore[arg-type]
            brand=BRAND,
            gtin=None,
            mpn=sku,
            identifier_exists=False,
            google_product_category=GOOGLE_PRODUCT_CATEGORY,
            product_type=product_class(product),
            product_details=[
                ("Strength", dose),
                ("Pack", pack),
                ("Intended use", "Laboratory research use only"),
            ],
            variant_label=label,
            condition="new",
            source=self.source,
        )

    def expand(self, catalog: dict[str, Any] | Iterable[dict[str, Any]]) -> Iterator[Product]:
        products = catalog.get("products") if isinstance(catalog, dict) else catalog
        for product in products or []:
            pid = str(product.get("id") or "")
            if not is_public(product):
                self._skip(pid, None, "draft/noindex/sample product")
                continue
            variants = product.get("variants") or []
            if not variants:
                self._skip(pid, None, "product without variants")
                continue
            description = describe(product, self.notes)  # once per product, notes not repeated
            for variant in variants:
                item = self.variant_to_product(product, variant, description)
                if item is not None:
                    yield item

    def run(self) -> list[Product]:
        return list(self.expand(self.fetch_catalog()))
